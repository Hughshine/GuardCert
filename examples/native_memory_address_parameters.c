void param_copy2(int *p,int *q,int start,int n,int m,int s,int u,int v,int alpha,int beta) {
  int i=start,j=77,k=91;
  for(;i<n;i++) for(j=0;j<m;j++)
    p[16*i+j+u+32]=q[16*i+j+v+33]*alpha+i*beta+j;
  param_out_i=i;param_out_j=j;param_out_k=k;
}
void param_negative2(int *p,int *q,int start,int n,int m,int s,int u,int v,int alpha,int beta) {
  int i=start,j=77,k=91;
  for(;i<n;i++) for(j=0;j<m;j++)
    p[1023-16*i-j-u]=q[1022-16*i-j-v]*alpha+i*beta+j;
  param_out_i=i;param_out_j=j;param_out_k=k;
}
void param_chain2(int *p,int *q,int start,int n,int m,int s,int u,int v,int alpha,int beta) {
  int i=start,j=77,k=91;
  for(;i<n;i++) for(j=0;j<m;j++) {
    p[16*i+j+u+32]=q[16*i+j+v+32]*alpha+i*beta+j;
    q[16*i+j+v+33]=p[16*i+j+u+32]+q[16*i+j+v+33]*beta+i-j+u-v;
  }
  param_out_i=i;param_out_j=j;param_out_k=k;
}
